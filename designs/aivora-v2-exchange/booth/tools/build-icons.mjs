#!/usr/bin/env node
// build-icons.mjs — regenerate ../assets/icons.js from the repo's installed lucide-react.
//
// Usage (from anywhere):
//   node designs/aivora-v2-exchange/booth/tools/build-icons.mjs [extra-icon-name ...]
//
// Reads the exact iconNode arrays out of lucide-react's ESM icon modules
// (node_modules/lucide-react/dist/esm/icons/<name>.js) without importing React,
// and writes a classic (non-module) script defining window.BoothIcons.
// Override the package location with LUCIDE_DIR=/path/to/lucide-react.

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BOOTH = path.resolve(HERE, "..");
const LUCIDE = process.env.LUCIDE_DIR
  ? path.resolve(process.env.LUCIDE_DIR)
  : path.resolve(BOOTH, "../../../node_modules/lucide-react");
const ICON_DIR = path.join(LUCIDE, "dist/esm/icons");
const OUT = path.join(BOOTH, "assets/icons.js");

// The icon set the booth pages use. Add names here (or pass them as CLI args) and re-run.
const NAMES = [
  "play", "pause", "check", "circle-check", "send", "message-circle", "reply", "link",
  "calendar-check", "clapperboard", "shield-check", "hand", "bot", "user-round", "square",
  "rotate-ccw", "qr-code", "languages", "x", "arrow-right", "wifi-off", "ban", "smartphone",
  "monitor", "tablet", "store", "map-pin", "timer", "eye", "badge-check", "mail", "scan-line",
  "chevron-right", "info", "triangle-alert", "circle-dashed", "lock", "globe", "calculator",
  "house",
];

// If a requested name is absent from this lucide version, use the closest existing icon.
// (With lucide-react 1.7.0 every name above exists, so this is only a safety net.)
const FALLBACKS = {
  "circle-check": "check-circle",
  "triangle-alert": "alert-triangle",
  "house": "home",
  "user-round": "user",
  "scan-line": "scan",
  "calendar-check": "calendar",
  "circle-dashed": "circle",
  "message-circle": "message-square",
};

// Convenience aliases exposed at runtime (old lucide names -> booth names).
const RUNTIME_ALIASES = {
  "home": "house",
  "alert-triangle": "triangle-alert",
  "check-circle": "circle-check",
};

const pkg = JSON.parse(fs.readFileSync(path.join(LUCIDE, "package.json"), "utf8"));
const license = fs.readFileSync(path.join(LUCIDE, "LICENSE"), "utf8");
const iscHead = license.split(/\n---\n/)[0].trim();
const copyright = (iscHead.match(/^Copyright.*$/m) || ["Copyright (c) Lucide Icons and Contributors"])[0];

const extra = process.argv.slice(2).filter((a) => /^[a-z0-9-]+$/.test(a));
const wanted = [...new Set([...NAMES, ...extra])];

function readIconNode(name, seen = []) {
  const file = path.join(ICON_DIR, `${name}.js`);
  if (!fs.existsSync(file)) return null;
  const src = fs.readFileSync(file, "utf8");
  const alias = src.match(/export\s*\{\s*default\s*\}\s*from\s*['"]\.\/([a-z0-9-]+)\.js['"]/);
  if (alias) {
    if (seen.includes(alias[1])) throw new Error(`alias loop at ${name}`);
    const r = readIconNode(alias[1], [...seen, name]);
    return r && { ...r, via: [name, ...r.via] };
  }
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\s*\n\s*const \w+ = createLucideIcon\(/);
  if (!m) throw new Error(`could not find __iconNode in ${file}`);
  // The literal is plain JSON-ish data (unquoted keys); evaluate it in an empty sandbox.
  const node = vm.runInNewContext(`(${m[1]})`, Object.create(null), { timeout: 200 });
  if (!Array.isArray(node)) throw new Error(`bad __iconNode in ${file}`);
  return { name, node, via: [] };
}

const esc = (v) => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const kebab = (k) => k.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

function toMarkup(node) {
  return node
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => ` ${kebab(k)}="${esc(v)}"`)
        .join("");
      return `<${tag}${a}/>`;
    })
    .join("");
}

const icons = {};
const mappings = [];
for (const name of wanted) {
  let r = readIconNode(name);
  if (!r && FALLBACKS[name]) {
    r = readIconNode(FALLBACKS[name]);
    if (r) mappings.push(`${name} -> ${FALLBACKS[name]} (missing in lucide-react ${pkg.version})`);
  }
  if (!r) {
    console.error(`!! icon "${name}" not found in lucide-react ${pkg.version}; add a FALLBACKS entry`);
    process.exitCode = 1;
    continue;
  }
  if (r.via.length) mappings.push(`${name} -> ${r.name} (alias in lucide-react ${pkg.version})`);
  icons[name] = toMarkup(r.node);
}

const header = `/*!
 * BoothIcons — inline SVG icons for the Aivora booth kit (classic script, no modules).
 * GENERATED by tools/build-icons.mjs from lucide-react ${pkg.version}. Do not edit by hand; re-run:
 *   node designs/aivora-v2-exchange/booth/tools/build-icons.mjs
 *
 * Icon artwork: Lucide (https://lucide.dev), ISC License.
 * ${copyright}
 *
 * Permission to use, copy, modify, and/or distribute this software for any
 * purpose with or without fee is hereby granted, provided that the above
 * copyright notice and this permission notice appear in all copies.
 *
 * THE SOFTWARE IS PROVIDED "AS IS" AND THE AUTHOR DISCLAIMS ALL WARRANTIES
 * WITH REGARD TO THIS SOFTWARE INCLUDING ALL IMPLIED WARRANTIES OF
 * MERCHANTABILITY AND FITNESS. IN NO EVENT SHALL THE AUTHOR BE LIABLE FOR
 * ANY SPECIAL, DIRECT, INDIRECT, OR CONSEQUENTIAL DAMAGES OR ANY DAMAGES
 * WHATSOEVER RESULTING FROM LOSS OF USE, DATA OR PROFITS, WHETHER IN AN
 * ACTION OF CONTRACT, NEGLIGENCE OR OTHER TORTIOUS ACTION, ARISING OUT OF
 * OR IN CONNECTION WITH THE USE OR PERFORMANCE OF THIS SOFTWARE.
 *
 * Some Lucide icons derive from Feather (https://feathericons.com),
 * MIT License, Copyright (c) 2013-present Cole Bemis.
 */`;

const body = `
(function (root) {
  "use strict";
  var ICONS = ${JSON.stringify(icons, null, 2)};
  var ALIASES = ${JSON.stringify(RUNTIME_ALIASES)};
  var warned = Object.create(null);
  var own = function (o, k) { return Object.prototype.hasOwnProperty.call(o, k); };
  function esc(v) {
    return String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
  }
  root.BoothIcons = {
    /** Inline SVG string for a lucide icon. Size it with CSS (e.g. .ic { width: 1em; height: 1em; }). */
    svg(name, cls = "ic") {
      // own-property lookups only, so names like "toString" are reported as unknown
      var key = own(ICONS, name) ? name : (own(ALIASES, name) ? ALIASES[name] : null);
      var inner = key ? ICONS[key] : "";
      if (!key && !warned[name]) {
        warned[name] = true;
        if (root.console) root.console.warn("BoothIcons: unknown icon \\"" + name + "\\"");
      }
      return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor"' +
        ' stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"' +
        ' focusable="false" class="' + esc(cls) + '"' + (key ? "" : ' data-missing-icon="' + esc(name) + '"') +
        ">" + inner + "</svg>";
    },
    has: function (name) {
      return own(ICONS, name) || own(ALIASES, name);
    },
    names: Object.keys(ICONS)
  };
})(typeof window !== "undefined" ? window : globalThis);
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header + "\n" + body);
console.log(`wrote ${path.relative(process.cwd(), OUT)} — ${Object.keys(icons).length} icons from lucide-react ${pkg.version}`);
if (mappings.length) console.log("name mappings:\n  " + mappings.join("\n  "));
else console.log("name mappings: none (all requested names exist verbatim)");
